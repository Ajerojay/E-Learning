-- One row per level the child has played. Parent progress reads stars from here.
create table if not exists public.quest_level_results (
  id bigint generated by default as identity primary key,
  child_id text not null,
  game_code text not null,
  level_index smallint not null check (level_index between 0 and 2),
  stars numeric not null check (stars >= 0 and stars <= 3),
  wrong_attempts integer not null default 0,
  time_left integer,
  finished boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (child_id, game_code, level_index)
);

alter table public.quest_level_results enable row level security;

drop policy if exists "app quest level results access" on public.quest_level_results;
create policy "app quest level results access"
  on public.quest_level_results
  for all
  using (true)
  with check (true);
