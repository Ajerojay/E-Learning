create table if not exists public.app_notifications (
  id bigint generated by default as identity primary key,
  recipient_role text not null check (recipient_role in ('parent', 'teacher')),
  recipient_id text not null,
  sender_role text check (sender_role in ('parent', 'teacher')),
  sender_id text,
  sender_name text,
  child_id text,
  child_name text,
  kind text not null default 'message',
  title text not null,
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists app_notifications_recipient_idx
  on public.app_notifications (recipient_role, recipient_id, created_at desc);

alter table public.app_notifications enable row level security;

drop policy if exists "app notifications access" on public.app_notifications;
create policy "app notifications access"
  on public.app_notifications for all using (true) with check (true);

do $$
begin
  alter publication supabase_realtime add table public.app_notifications;
exception
  when duplicate_object then null;
end $$;

notify pgrst, 'reload schema';
